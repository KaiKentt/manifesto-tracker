// Combines supabase/schema.sql + supabase/seed.sql into supabase/setup.sql,
// a single file you can paste into the Supabase SQL Editor.
// Usage: npm run db:bundle
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase");
const schema = readFileSync(join(dir, "schema.sql"), "utf8");
const seed = readFileSync(join(dir, "seed.sql"), "utf8");

const out = `-- GENERATED by scripts/bundle-sql.mjs — edit schema.sql / seed.sql instead.
-- Paste this whole file into Supabase → SQL Editor → New query → Run.

${schema}

${seed}
`;
writeFileSync(join(dir, "setup.sql"), out);
console.log("Wrote supabase/setup.sql");
